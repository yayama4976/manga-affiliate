def build_prompt(it):
    return f"""楽天商品の紹介を、笑える4コマ漫画の台本にしてください。JSONのみ出力。
商品名: {it['itemName']} / 価格: {it['itemPrice']}円 / レビュー: {it['reviewAverage']}({it['reviewCount']}件)
キャラ: hero=ちょっとズボラな在宅ワーカーの男性(タクミ) / neko=物知りで毒舌なネコ店長
構成: 1=読者が「あるある」と共感する悩み 2=悪化・失敗談 3=商品登場 4=意外なオチ(ネコ店長の一言で落とす)
ルール:
- 各コマのセリフはちょうど2個。1個目は必ずhero、2個目は必ずneko。1個25字以内
- ネコ店長は毒舌だが愛がある。短く鋭いツッコミ、語尾は「ニャ」。説明口調にしない
- 声に出して自然な日本語にする(翻訳調・不自然な助詞・原因と結果のズレは禁止)
- 悪い例「コップに水置いたらこぼした」→良い例「コップの水をキーボードにこぼした…」
- 商品情報は3コマ目だけで触れる。誇大表現・効果効能の断定禁止。商品情報にない事実は書かない
- 4コマ目は読者がクスッと笑うオチにする
- 【最優先】セリフのtextは話す内容だけ。話者名や「」『』は付けない(名前は自動で表示される)。キャプションも同じ
- ネコ店長は各コマ1匹だけ。他の猫・猫の絵・猫のぬいぐるみ・猫の写真は描かない。image_promptでは猫を neko とだけ書き、cat/cats/kitten は使わない
- 各コマに描く人物はheroだけ(1人)。他の人物は入れない
- 割引率・期間限定・福袋・セール・ポイント倍率・期限は書かない(期限後に事実とずれるため)。商品のことは機能と価格だけにする
- キャプションは20字以内。セリフやキャプションに hero/neko は使わず、タクミ/ネコ店長と書く
- x_postは、X用の投稿文。1行目はネコ店長の一番面白いセリフを「ネコ店長「…」」の形で入れる。2〜3行目で悩みを一言。絵文字を1〜2個。ハッシュタグ・URL・誘導の文は入れない(別で足す)。全体で100字以内
- 書いたあと全セリフを読み直し、不自然なら直してから出力
- image_promptにはキャラの髪型・服装・毛色・顔つきを書かない。背景・構図・表情・ポーズだけ書く
image_promptは英語で、そのコマの情景・構図・表情を具体的に(文字は入れない、キャラ名は hero/neko と書く)
形式: {{"title":"悩み系キーワード入りタイトル",
"panels":[{{"image_prompt":"...","lines":[{{"who":"hero","text":"..."}},{{"who":"neko","text":"..."}}],"caption":""}}x4],
"points":["選ぶポイント3つ"],"for":"向く人","not_for":"向かない人","x_post":"..."}}"""
